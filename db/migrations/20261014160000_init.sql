-- Schéma initial sur Cloud SQL (Postgres), repris à l'identique de la base Supabase du 14/10/2026.
-- Déjà appliquée sur biirb-db1 (base « brb ») par un utilisateur cloudsqlsuperuser temporaire.
-- Attribuer un rôle à un nouvel utilisateur IAM (un « grant » en SQL est refusé, même avec postgres) :
--   gcloud sql users assign-roles <email> --instance=biirb-db1 --type=CLOUD_IAM_USER --database-roles=brb_admin
--   (compte de service Cloud Run : --type=CLOUD_IAM_SERVICE_ACCOUNT --database-roles=brb_app)
-- Les migrations suivantes s'exécutent dans Cloud SQL Studio (Console GCP → SQL → biirb-db1),
-- connecté avec son compte Google, et commencent par « set role brb_admin; » pour que brb_admin
-- reste propriétaire des tables.

-- Rôles (sans connexion directe : on les attribue aux utilisateurs IAM) :
--   brb_admin → propriétaire du schéma, pour les migrations et le seed (développeurs).
--   brb_app   → droits minimaux de l'application (compte de service Cloud Run).
create role brb_admin nologin;
create role brb_app nologin;
grant brb_admin to current_user;
grant usage, create on schema public to brb_admin;
grant usage on schema public to brb_app;

set role brb_admin;

-- (« user » est un mot réservé en Postgres, d'où « users ».)
create table users (
  id uuid primary key default gen_random_uuid(),
  username text not null unique check (username ~ '^[a-z0-9_]{3,30}$'),
  display_name text not null check (char_length(display_name) between 1 and 60),
  avatar_url text check (avatar_url ~ '^https://'),
  created_at timestamptz not null default now(),
  email text unique check (email = lower(email) and char_length(email) <= 254),
  password_hash text check (password_hash like '$2%'),
  location text check (char_length(location) between 1 and 80),
  avatar_seed text check (avatar_seed ~ '^[A-Za-z0-9_-]{1,64}$')
);

create table archetype (
  id integer generated by default as identity primary key,
  slug varchar(40) not null unique
);

create table tag (
  id integer generated by default as identity primary key,
  country_code char(2) not null,
  state_code varchar(10),
  city varchar(100)
);

create table post (
  id integer generated by default as identity primary key,
  author_id uuid not null references users (id) on delete cascade,
  title varchar(100) not null,
  photo_url text not null,
  photo_alt varchar(200) not null,
  short_description varchar(252) not null,
  long_description text not null,
  destination_country_code char(2) not null,
  destination_state_code varchar(10),
  destination_city varchar(100),
  start_date date not null,
  end_date date not null,
  archetype_id integer not null references archetype (id),
  created_at timestamptz not null default now()
);

create index post_author_id_created_at_idx on post (author_id, created_at desc);

create table post_tag (
  post_id integer references post (id) on delete cascade,
  tag_id integer references tag (id) on delete cascade,
  primary key (post_id, tag_id)
);

